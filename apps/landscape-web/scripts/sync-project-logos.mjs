import { execFile } from "node:child_process";
import { mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const ROOT = process.cwd();
const DATA_PATH = path.resolve(ROOT, "../../data/agentic-ai-projects.csv");
const OUTPUT_DIR = path.join(ROOT, "public", "project-logos");
const MANIFEST_PATH = path.join(ROOT, "lib", "project-logo-manifest.ts");
const CONCURRENCY = 4;
const MAX_ATTEMPTS = 3;
const execFileAsync = promisify(execFile);

function parseCsv(source) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    const next = source[index + 1];

    if (character === '"') {
      if (quoted && next === '"') {
        cell += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === "," && !quoted) {
      row.push(cell);
      cell = "";
    } else if ((character === "\n" || character === "\r") && !quoted) {
      if (character === "\r" && next === "\n") index += 1;
      row.push(cell);
      if (row.some(Boolean)) rows.push(row);
      row = [];
      cell = "";
    } else {
      cell += character;
    }
  }

  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }

  const [headers, ...records] = rows;
  return records.map((record) =>
    Object.fromEntries(
      headers.map((header, index) => [header, record[index] ?? ""]),
    ),
  );
}

function extensionFor(contentType) {
  if (contentType.includes("image/jpeg")) return "jpg";
  if (contentType.includes("image/webp")) return "webp";
  if (contentType.includes("image/gif")) return "gif";
  return "png";
}

function pause(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function downloadLogo(owner) {
  let lastError;
  const downloadPath = path.join(OUTPUT_DIR, `.${owner}.download`);

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt += 1) {
    try {
      const { stdout: contentType } = await execFileAsync("curl", [
        "--location",
        "--fail",
        "--silent",
        "--show-error",
        "--max-time",
        "20",
        "--retry",
        "2",
        "--user-agent",
        "agentic-ai-landscape-logo-sync",
        "--output",
        downloadPath,
        "--write-out",
        "%{content_type}",
        `https://github.com/${encodeURIComponent(owner)}.png?size=160`,
      ]);

      if (!contentType.startsWith("image/")) {
        throw new Error(`Unexpected content type: ${contentType || "missing"}`);
      }

      const bytes = await readFile(downloadPath);
      if (bytes.length < 100) {
        throw new Error(`Image response is too small: ${bytes.length} bytes`);
      }

      const filename = `${owner}.${extensionFor(contentType)}`;
      await rename(downloadPath, path.join(OUTPUT_DIR, filename));
      return filename;
    } catch (error) {
      lastError = error;
      await unlink(downloadPath).catch(() => {});
      if (attempt < MAX_ATTEMPTS) await pause(attempt * 750);
    }
  }

  throw lastError;
}

async function runPool(items, worker) {
  const results = new Map();
  let cursor = 0;

  async function next() {
    while (cursor < items.length) {
      const item = items[cursor];
      cursor += 1;

      try {
        results.set(item, { value: await worker(item) });
        console.log(`cached ${item}`);
      } catch (error) {
        results.set(item, { error });
        console.error(`failed ${item}: ${error.message}`);
      }
    }
  }

  await Promise.all(
    Array.from({ length: Math.min(CONCURRENCY, items.length) }, () => next()),
  );
  return results;
}

const csv = await readFile(DATA_PATH, "utf8");
const owners = [
  ...new Set(
    parseCsv(csv.replace(/^\uFEFF/, ""))
      .filter((record) =>
        ["keep", "add"].includes(
          record.landscape_action.trim().toLowerCase(),
        ),
      )
      .map((record) => record.repo_name.split("/")[0].toLowerCase())
      .filter((owner) => /^[a-z0-9-]+$/.test(owner)),
  ),
].sort();

await mkdir(OUTPUT_DIR, { recursive: true });
const results = await runPool(owners, downloadLogo);
const manifest = Object.fromEntries(
  [...results]
    .filter(([, result]) => result.value)
    .map(([owner, result]) => [owner, result.value]),
);
const manifestSource = [
  "// Generated by `npm run sync:logos`.",
  `export const PROJECT_LOGO_FILES: Readonly<Record<string, string>> = ${JSON.stringify(
    manifest,
    null,
    2,
  )};`,
  "",
].join("\n");
const temporaryManifest = `${MANIFEST_PATH}.tmp`;
await writeFile(temporaryManifest, manifestSource);
await rename(temporaryManifest, MANIFEST_PATH);

const failures = [...results].filter(([, result]) => result.error);
console.log(
  `Project logos: ${Object.keys(manifest).length} cached, ${failures.length} failed.`,
);

if (failures.length) process.exitCode = 1;
